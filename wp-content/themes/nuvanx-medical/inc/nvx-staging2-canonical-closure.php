<?php
/**
 * Canonical closure for non-public QA environments.
 *
 * Staging2 remains noindex, but approved public routes expose the URL that will
 * be canonical in Production. Protected working-name routes stay without a
 * canonical because they must not imply a publishable production counterpart.
 *
 * @package nuvanx-medical
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Determines whether the current strategy route is approved for publication.
 *
 * @return bool `true` only when the catalog exists, the key is valid, and review_status is exactly 'approved_for_publication'.
 */
function nvx_staging2_canonical_is_approved_strategy(): bool {
	if ( ! function_exists( 'nvx_strategy_current_page_key' ) || ! function_exists( 'nvx_strategy_page_catalog' ) ) {
		return false;
	}

	$key     = nvx_strategy_current_page_key();
	$catalog = nvx_strategy_page_catalog();

	return null !== $key
		&& 'approved_for_publication' === ( $catalog[ $key ]['review_status'] ?? null );
}

/**
 * Builds the public production canonical URL for eligible current-page requests.
 *
 * @return string The production URL for the current path, or an empty string when the request is excluded.
 */
function nvx_staging2_public_canonical_url(): string {
	$is_strategy_page = function_exists( 'nvx_strategy_current_page_key' ) && null !== nvx_strategy_current_page_key();
	$is_protected     = $is_strategy_page && ! nvx_staging2_canonical_is_approved_strategy();

	if ( $is_protected || is_404() || is_search() || is_preview() ) {
		return '';
	}

	if ( ! is_front_page() && ! is_home() && ! is_singular() ) {
		return '';
	}

	if ( function_exists( 'nvx_seo_current_path' ) ) {
		$path = nvx_seo_current_path();
	} else {
		$uri  = isset( $_SERVER['REQUEST_URI'] ) ? (string) $_SERVER['REQUEST_URI'] : '/';
		$path = (string) wp_parse_url( $uri, PHP_URL_PATH );
	}

	$path = '/' . trim( (string) $path, '/' );
	if ( '/' !== $path ) {
		$path .= '/';
	}

	return 'https://nuvanx.com' . $path;
}

/**
 * Open Graph URL on non-production: point social previews at the production host
 * for approved routes. The HTML link[rel=canonical] is owned solely by
 * nvx-document-governance (wp_head emission + wpseo_canonical suppress). Do not
 * re-attach this function to wpseo_canonical — that race produced dual policies
 * at priority 1000.
 *
 * @param mixed $url The Open Graph URL generated by Yoast.
 * @return mixed Production public URL on non-production; original value otherwise.
 */
function nvx_staging2_filter_public_opengraph_url( $url ) {
	if ( ! function_exists( 'nvx_seo_is_nonproduction_environment' ) || ! nvx_seo_is_nonproduction_environment() ) {
		return $url;
	}

	return nvx_staging2_public_canonical_url();
}
add_filter( 'wpseo_opengraph_url', 'nvx_staging2_filter_public_opengraph_url', 1000 );
